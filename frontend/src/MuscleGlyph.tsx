export default function MuscleGlyph({
  group,
  groups,
  selected = false,
}: {
  group: MuscleGroup;
  groups?: MuscleGroup[];
  selected?: boolean;
}) {
  const targetMask = (groups?.length ? groups : [group]).reduce(
    (mask, item) => mask | targets[item],
    0,
  );
  return (
    <svg
      viewBox="0 0 112 180"
      width="56"
      height="90"
      aria-hidden="true"
      focusable="false"
      className="personal-muscle-glyph"
    >
      {dots.map(([x, y, mask]) => (
        <circle
          key={`${x}-${y}`}
          cx={x}
          cy={y}
          r={1.35}
          fill={
            mask & targetMask
              ? "var(--ds-accent, #e8492d)"
              : "var(--muscle-base, #c4c3bd)"
          }
          opacity={selected || mask & targetMask ? 1 : 0.72}
        />
      ))}
    </svg>
  );
}
